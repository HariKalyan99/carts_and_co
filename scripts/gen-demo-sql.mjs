// Generates the demo-studio migration from scripts/seed-data.js.
// Usage: node scripts/gen-demo-sql.mjs > supabase/migrations/<timestamp>_demo_data.sql
import { createSeed } from './seed-data.js'

const { creators, batches, orders, comments, outbox } = createSeed()

const lit = (v) => {
  if (v === null || v === undefined) return 'null'
  if (typeof v === 'number') return String(v)
  return `'${String(v).replaceAll("'", "''")}'`
}
const json = (v) => `${lit(JSON.stringify(v))}::jsonb`
const textArray = (arr) => `array[${arr.map(lit).join(', ')}]::text[]`

const insert = (table, cols, rows) =>
  rows.length === 0
    ? ''
    : `insert into app.${table} (${cols.join(', ')}) values\n${rows.map((r) => `  (${r.join(', ')})`).join(',\n')};\n`

const out = [
  '-- Demo studios (generated by scripts/gen-demo-sql.mjs). Safe to re-run: skips if present.',
  "do $$ begin if exists (select 1 from app.creators where id = 'seed_sarah') then return; end if;",
  '',
  insert(
    'creators',
    ['id', 'slug', 'display_name', 'studio_name', 'city', 'bio', 'accent_hue', 'emoji', 'created_at'],
    creators.map((c) => [c.id, c.slug, c.displayName, c.studioName, c.city, c.bio, c.accentHue, c.emoji, c.createdAt].map(lit)),
  ),
  insert(
    'batches',
    ['id', 'code', 'creator_id', 'title', 'tagline', 'description', 'unit_label', 'price', 'funding_goal', 'max_quantity', 'funding_deadline', 'cover_hue', 'stage', 'stage_history', 'created_at'],
    batches.map((b) => [
      lit(b.id), lit(b.code), lit(b.creatorId), lit(b.title), lit(b.tagline), lit(b.description), lit(b.unitLabel),
      lit(b.price), lit(b.fundingGoal), lit(b.maxQuantity), lit(b.fundingDeadline), lit(b.coverHue), lit(b.stage),
      json(b.stageHistory), lit(b.createdAt),
    ]),
  ),
  insert(
    'orders',
    ['id', 'number', 'batch_id', 'buyer_name', 'email', 'quantity', 'address', 'city', 'pincode', 'status', 'tracking_token', 'tier', 'packaged_at', 'courier', 'awb', 'shipped_at', 'created_at'],
    orders.map((o) => [
      lit(o.id), lit(o.number), lit(o.batchId), lit(o.buyerName), lit(o.email), lit(o.quantity), lit(o.address), lit(o.city),
      lit(o.pincode), lit(o.status), lit(o.trackingToken), lit(o.tier), lit(o.packagedAt), lit(o.courier), lit(o.awb),
      lit(o.shippedAt), lit(o.createdAt),
    ]),
  ),
  // Parents first so the self-reference is satisfied row by row.
  insert(
    'comments',
    ['id', 'batch_id', 'update_key', 'parent_id', 'author', 'body', 'created_at'],
    [...comments]
      .sort((a, b) => Number(Boolean(a.parentId)) - Number(Boolean(b.parentId)))
      .map((c) => [lit(c.id), lit(c.batchId), lit(c.updateKey), lit(c.parentId), json(c.author), lit(c.body), lit(c.createdAt)]),
  ),
  insert(
    'outbox',
    ['id', 'batch_id', 'kind', 'stage', 'subject', 'body', 'photo_url', 'recipients', 'sent_at'],
    outbox.map((m) => [lit(m.id), lit(m.batchId), lit(m.kind), lit(m.stage), lit(m.subject), lit(m.body), lit(m.photoUrl), textArray(m.recipients), lit(m.sentAt)]),
  ),
  'end $$;',
]

console.log(out.join('\n'))
